import { mkdir, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { VOICE_ASSETS } from '../src/audio/manifest.js';

const root = resolve(import.meta.dirname, '..');
const outputDir = resolve(root, 'src/audio');
const region = process.env.AZURE_SPEECH_REGION || 'eastus';
const voice = process.env.AZURE_SPEECH_VOICE || 'zh-CN-XiaoxiaoNeural';
const key = process.env.AZURE_SPEECH_KEY;
const endpoint = `https://${region}.tts.speech.microsoft.com/cognitiveservices/v1`;
const escapeXML = value => String(value).replace(/[<>&"']/g, ch => ({ '<': '&lt;', '>': '&gt;', '&': '&amp;', '"': '&quot;', "'": '&apos;' }[ch]));

if (!key) {
  console.error('缺少 AZURE_SPEECH_KEY。请在终端用 read -s AZURE_SPEECH_KEY 输入，或从 Azure Speech 资源的“密钥和终结点”页面复制后导出。');
  process.exit(1);
}

await mkdir(outputDir, { recursive: true });
for (const [id, asset] of Object.entries(VOICE_ASSETS)) {
  const ssml = `<speak version="1.0" xml:lang="zh-CN" xmlns="http://www.w3.org/2001/10/synthesis"><voice name="${voice}"><prosody rate="-8%" pitch="+1st">${escapeXML(asset.text)}</prosody></voice></speak>`;
  const response = await fetch(endpoint, {
    method: 'POST',
    headers: { 'Ocp-Apim-Subscription-Key': key, 'Content-Type': 'application/ssml+xml', 'X-Microsoft-OutputFormat': 'audio-24khz-48kbitrate-mono-mp3', 'User-Agent': 'little-focus-island-asset-generator' },
    body: ssml,
  });
  if (!response.ok) {
    const detail = (await response.text()).slice(0, 300);
    throw new Error(`${id}: Azure TTS 请求失败（${response.status}）${detail ? ` ${detail}` : ''}`);
  }
  const bytes = Buffer.from(await response.arrayBuffer());
  if (bytes.length < 1024) throw new Error(`${id}: Azure 返回的音频过小，未写入文件`);
  await writeFile(resolve(outputDir, `${id}.mp3`), bytes);
  console.log(`已生成 ${id}.mp3`);
}

const manifest = `// Generated by Azure Speech once; runtime playback is local-only.\nexport const GENERATED_VOICE_ASSETS = true;\nexport const VOICE_ASSETS = ${JSON.stringify(Object.fromEntries(Object.entries(VOICE_ASSETS).map(([id, asset]) => [id, { text: asset.text, path: `/src/audio/${id}.mp3` }])), null, 2)};\n`;
await writeFile(resolve(outputDir, 'manifest.js'), manifest);
console.log(`完成：${Object.keys(VOICE_ASSETS).length} 个本地 MP3，区域 ${region}，音色 ${voice}。`);
