import { mkdir, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const outputDir = resolve(root, 'src/audio');
const model = process.env.OPENAI_TTS_MODEL || 'gpt-4o-mini-tts';
const voice = process.env.OPENAI_TTS_VOICE || 'marin';
const instructions = process.env.OPENAI_TTS_INSTRUCTIONS || 'Use warm, calm, encouraging Mandarin Chinese suitable for a 7-year-old child. Speak slowly, with short pauses between sentences. Never sound urgent, evaluative, or competitive. Keep the exact words provided; do not add commentary.';
const assets = {
  'home-welcome': '欢迎来到小小专注岛。今天，我们只做一件小事。',
  'search-rule': '找出所有的小兔子。找完以后，点找好了。',
  'search-strategy': '一行一行找，找完再检查。',
  'stop-rule': '小兔出现，点请过桥。狐狸出现，等它自己离开。',
  'stop-strategy': '先认清是谁，再决定要不要动手。',
  'memory-rule': '先看包裹的顺序，记好以后，按同样的顺序点选。',
  'memory-strategy': '在心里说一遍，再按顺序行动。',
  'memory-recall': '请按刚才记住的顺序，点选包裹。',
  'practice-start': '先试一小轮。弄懂规则以后，再开始。',
  'sound-on': '语音已开启，慢慢来。',
  'search-success': '小兔子都找到啦！',
  'search-coach': '再记住一个办法：一行一行找。',
  'stop-success': '你会看清再行动啦！',
  'stop-coach': '遇到狐狸，让它自己离开。',
  'memory-success': '包裹按顺序送到啦！',
  'memory-coach': '下次试试，在心里说一遍顺序。',
};

if (!process.env.OPENAI_API_KEY) {
  console.error('缺少 OPENAI_API_KEY。请在本地环境变量中配置后再运行 npm run voice:generate。');
  process.exit(1);
}

await mkdir(outputDir, { recursive: true });
for (const [id, text] of Object.entries(assets)) {
  const response = await fetch('https://api.openai.com/v1/audio/speech', {
    method: 'POST',
    headers: { Authorization: `Bearer ${process.env.OPENAI_API_KEY}`, 'Content-Type': 'application/json' },
    body: JSON.stringify({ model, voice, input: text, instructions, response_format: 'mp3', speed: 0.86 }),
  });
  if (!response.ok) throw new Error(`${id}: TTS 请求失败（${response.status}）`);
  await writeFile(resolve(outputDir, `${id}.mp3`), Buffer.from(await response.arrayBuffer()));
  console.log(`已生成 ${id}.mp3`);
}

const manifest = `// Generated by npm run voice:generate.\nexport const GENERATED_VOICE_ASSETS = true;\nexport const VOICE_ASSETS = ${JSON.stringify(Object.fromEntries(Object.entries(assets).map(([id, text]) => [id, { text, path: `/src/audio/${id}.mp3` }])), null, 2)};\n`;
await writeFile(resolve(outputDir, 'manifest.js'), manifest);
console.log(`完成：${Object.keys(assets).length} 个本地 MP3，模型 ${model}，音色 ${voice}。`);
